const catalogs: Record<ResellerLocale, Record<string, string>> = { en, ur };

export function translate(locale: ResellerLocale, key: string, vars?: Record<string, string>) {
  let text = catalogs[locale][key] ?? catalogs.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
}

export function readStoredLocale(): ResellerLocale {
  if (typeof window === "undefined") return "en";
  try {
    const raw = localStorage.getItem(RESELLER_LOCALE_KEY);
    return raw === "ur" ? "ur" : "en";
  } catch {
    return "en";
  }
}

export function storeLocale(locale: ResellerLocale) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(RESELLER_LOCALE_KEY, locale);
  } catch {
    /* ignore */
  }
}
